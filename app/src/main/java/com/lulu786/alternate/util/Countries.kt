    /**
     * Regions that share one dial code. The first digits of the national number tell them apart ([rules], first match wins);
     * a number matching no rule is [default]'s. When [strict] is false the SIM country gets to decide those leftovers instead.
     */
    private class Shared(val default: String, val strict: Boolean, val rules: List<Pair<String, List<String>>>)

    private val SHARED = mapOf(
        // +1: US unless the area code is Canadian. Territories (Bahamas 242, Puerto Rico 787 and 939, ...) have an entry per area code.
        "1" to Shared("US", true, listOf("CA" to CANADA_AREA_CODES)),
        "7" to Shared("RU", true, listOf("KZ" to listOf("6", "7"))),
        "39" to Shared("IT", true, listOf("VA" to listOf("06698"))),
        "44" to Shared("GB", false, listOf(
            "GG" to listOf("1481", "7781", "7839", "7911"), "JE" to listOf("1534", "7509", "7797", "7829", "7937"),
            "IM" to listOf("1624", "7524", "7624", "7924"),
        )),
        "47" to Shared("NO", true, listOf("SJ" to listOf("79"))),
        "61" to Shared("AU", true, listOf("CC" to listOf("89162"), "CX" to listOf("89164"))),
        "212" to Shared("MA", true, listOf("EH" to listOf("5288", "5289"))),
        "262" to Shared("RE", true, listOf("YT" to listOf("269", "639"))),
        "290" to Shared("SH", true, listOf("TA" to listOf("8"))),
        "358" to Shared("FI", true, listOf("AX" to listOf("18"))),
        "599" to Shared("CW", true, listOf("BQ" to listOf("3", "4", "7"))),
    )

    private val byCode = all.associateBy { it.code }
    // Longest dial code first so "1242" (Bahamas) wins over "1" for +1 242 ...
    private val byDialLength = all.sortedByDescending { it.dialCode.length }

    fun byCode(code: String): Country? = byCode[code.uppercase()]

    /** The entry a stored number belongs to: a few countries (Puerto Rico, Dominican Republic, Jamaica) have one per area code. */
    fun forNumber(code: String, full: String): Country? = all.firstOrNull { it.code.equals(code, true) && full.startsWith(it.dialCode) } ?: byCode(code)

    /**
     * Splits a number that starts with a dial code (digits only, no '+') into country and national part.
     * Regions sharing a dial code are told apart by [SHARED]; [preferred] (SIM/network country) only settles what is left.
     */
    fun split(digits: String, preferred: String?): Pair<Country, String>? {
        val matches = byDialLength.filter { digits.startsWith(it.dialCode) && digits.length > it.dialCode.length }
        if (matches.isEmpty()) return null
        val longest = matches.maxOf { it.dialCode.length }
        val top = matches.filter { it.dialCode.length == longest }
        val national = digits.substring(longest)
        val shared = if (top.size > 1) SHARED[top[0].dialCode] else null
        val byRule = shared?.let { sh ->
            sh.rules.firstOrNull { (_, prefixes) -> prefixes.any(national::startsWith) }?.first ?: sh.default.takeIf { sh.strict }
        }
        val pick = byRule?.let(byCode::get) ?: top.firstOrNull { it.code.equals(preferred, true) }
            ?: top.firstOrNull { it.code == shared?.default } ?: top.first()
        return pick to national
    }
